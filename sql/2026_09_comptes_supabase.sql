-- ── 9. Amorçage : un premier super admin ───────────────────────────────
-- REMPLACE le mot de passe ci-dessous, puis exécute UNE FOIS. Sans ce
-- compte, aucune administration n'est possible depuis l'app.
insert into public.app_users (login, full_name, password_hash, role)
select 'pamela', 'Pamela — Super Admin',
       crypt('CHANGE-MOI-AVANT-EXECUTION', gen_salt('bf', 12)), 0
where not exists (select 1 from public.app_users where role = 0);

